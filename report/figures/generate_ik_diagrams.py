"""Generate editable TikZ illustrations of the analytical arm IK geometry.

The two spatial views use the same geometry and parallel projection, expressed
in different coordinate frames. The base view retains a faint arm outline;
the shoulder view isolates the two invariants of the joint-2 rotation.
Run with Python 3 + NumPy; compiling the generated TikZ needs neither Python
nor shell escape. Numerical checks compare the geometry with the actual URDF.
"""
from pathlib import Path
import math
import xml.etree.ElementTree as ET
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PI = math.pi
Q1, Q2, Q3 = np.deg2rad([40., 25., 75.])
GAMMA = PI / 6
A1, A2, D1, D2, D3, D4 = .8, 2., 1., 1.25, .75, 2.5
PROJ = np.array([[1., .45, 0.], [0., .5, 1.]])
EX, EY, EZ = np.eye(3)


def rx(t):
    c, s = math.cos(t), math.sin(t)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])


def ry(t):
    c, s = math.cos(t), math.sin(t)
    return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])


def rz(t):
    c, s = math.cos(t), math.sin(t)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def rotation(axis, angle):
    axis = np.asarray(axis, float)
    axis /= np.linalg.norm(axis)
    x, y, z = axis
    skew = np.array([[0, -z, y], [z, 0, -x], [-y, x, 0]])
    return np.eye(3) + math.sin(angle)*skew + (1-math.cos(angle))*(skew@skew)


R0 = rz(Q1) @ rx(GAMMA)  # Auxiliary shoulder frame in the base frame.
R2 = R0 @ ry(Q2)
R3 = R2 @ rz(Q3)
O = np.zeros(3)
B = D1 * EZ
J1 = .5 * EZ
S = rz(Q1) @ np.array([A1, 0., D1])
G = S + D2 * R2 @ EY
E = G + A2 * R2 @ EX
H = E + D3 * R2 @ EZ  # Geometric corner on the elbow axis; not a new joint.
J4 = H + 1.5 * R3 @ EX
W = H + D4 * R3 @ EX
R = R0.T @ (W-S)
AVAL = A2 + D4 * math.cos(Q3)
U = np.array([AVAL, D2 + D4*math.sin(Q3), D3])


def pt(v):
    return '(' + ','.join(f'{float(x):.5f}' for x in v) + ')'


class Panel:
    def __init__(self, filename, shift, origin=O, orientation=np.eye(3),
                 scale=1.18, width=8.4, height=7.4):
        self.filename = filename
        self.shift = np.asarray(shift, float)
        self.origin = np.asarray(origin, float)
        self.orientation = orientation
        self.scale = scale
        self.lines = [
            '% Generated by generate_ik_diagrams.py; ordinary editable TikZ.',
            r'\begin{tikzpicture}[x=1cm,y=1cm,>=Latex,font=\footnotesize,',
            r' every node/.style={inner sep=1pt},',
            r' axis/.style={line width=.65pt,-{Latex[length=1.7mm]}},',
            r' construction/.style={dhgray!65,densely dashed,line width=.4pt},',
            r' vector/.style={dhpurple,line width=.9pt,-{Latex[length=2mm]}}]',
            rf'\path[use as bounding box] (0,0) rectangle ({width},{height});'
        ]

    def xy(self, p):
        return self.shift + self.scale * PROJ @ self.orientation.T @ (np.asarray(p)-self.origin)

    def line(self, p, q, style):
        self.lines.append(r'\draw['+style+'] '+pt(p)+' -- '+pt(q)+';')

    def worldline(self, p, q, style):
        self.line(self.xy(p), self.xy(q), style)

    def label(self, p, text, opts=''):
        self.lines.append(r'\node['+opts+'] at '+pt(p)+' {'+text+'};')

    def dot(self, p, color='dhink', radius='1.5pt', white=False):
        self.lines.append(r'\filldraw[draw='+color+',fill='+('white' if white else color)+'] '
                          +pt(self.xy(p))+r' circle[radius='+radius+'];')

    def curve(self, points, style):
        self.lines.append(r'\draw['+style+'] '+' -- '.join(pt(self.xy(p)) for p in points)+';')

    def axis(self, origin, direction, length, label, color, offset=(0., 0.)):
        end = origin + length*np.asarray(direction)
        self.worldline(origin, end, 'axis,'+color)
        self.label(self.xy(end)+offset, label, 'text='+color+',fill=white,inner sep=.5pt')

    def links(self, base=False):
        points = [O, B, S, G, E, H, W] if base else [S, G, E, H, W]
        self.curve(points, 'dhgray!45,line width=1pt,line cap=round,line join=round')

    def save(self):
        self.lines.append(r'\end{tikzpicture}')
        (HERE/self.filename).write_text('\n'.join(self.lines)+'\n')


# (a) The physical geometry expressed in base_link.
p = Panel('ik_base_frame.tex', [2.0, .72])
p.links(base=True)
p.worldline(O, W, 'vector')
p.label(p.xy(.52*W)+[-.48,.13], r'$p_w$', 'text=dhpurple,fill=white')
p.axis(O, EX, 1.15, r'$x_0$', 'dhred', (.15,-.12))
p.axis(O, EY, 1.1, r'$y_0$', 'dhgreen', (.12,.06))
p.axis(O, EZ, 1.55, r'$z_0$', 'dhblue', (-.16,.10))
p.worldline(O, 1.45*rz(Q1)@EX, 'construction')
p.label(p.xy(1.45*rz(Q1)@EX)+[.16,.04], r'$\bar x$', 'text=dhgray')
p.curve([.92*rz(t)@EX for t in np.linspace(0,Q1,35)],
        'dhpurple,line width=.75pt,-{Latex[length=1.6mm]}')
p.label(p.xy(.95*rz(Q1/2)@EX)+[.39,-.03], r'$q_1$', 'text=dhpurple')

# Fixed roll at S: y-bar is after Rz(q1), before Rx(gamma).
yb = rz(Q1)@EY
ys = R0@EY
p.worldline(S, S+1.65*yb, 'construction')
p.label(p.xy(S+1.65*yb)+[-.18,.02], r'$\bar y$', 'text=dhgray,fill=white')
p.axis(S, ys, 1.65, r'$y_s$', 'dhgreen', (-.16,.10))
p.axis(S, R0@EX, 1.15, r'$x_s$', 'dhred', (.15,-.10))
p.axis(S, R0@EZ, 1.35, r'$z_s$', 'dhblue', (-.16,.12))
p.curve([S+.97*rz(Q1)@rx(t)@EY for t in np.linspace(0,GAMMA,45)],
        'dhpurple,line width=.75pt,-{Latex[length=1.5mm]}')
gmid = p.xy(S+.97*rz(Q1)@rx(GAMMA/2)@EY)
p.line(gmid+[-.57,.64], gmid+[-.05,.03], 'dhpurple!70,line width=.4pt')
p.label(gmid+[-1.0,.80], r'$\gamma$', 'text=dhpurple')
for point in [O,S]:
    p.dot(point, radius='1.4pt')
p.dot(E, 'dhgray!55', radius='1pt')
p.dot(W, 'dhpurple', '2pt', white=True)
p.label(p.xy(O)+[-.18,-.23], r'$O_0$')
p.label(p.xy(S)+[.12,-.25], r'$S$', 'anchor=north,fill=white')
p.label(p.xy(W)+[.20,.10], r'$W$', 'anchor=west,text=dhpurple')
p.save()


# (b) Isolate rotation about y_s: its axial coordinate and norm are invariant.
p = Panel('ik_shoulder_frame.tex', [1.25,2.35], origin=S, orientation=R0)
center = S + R0@np.array([0., U[1], 0.])
w_zero = S + R0@U
p.worldline(center, w_zero, 'construction')
p.worldline(center, W, 'construction')
p.curve([S+R0@ry(t)@U for t in np.linspace(0,Q2,50)],
        'dhpurple!70,densely dashed,line width=.7pt,-{Latex[length=1.5mm]}')
p.worldline(S, w_zero, 'dhgold,line width=.75pt,-{Latex[length=1.7mm]}')
p.dot(w_zero, 'dhgold', '1.4pt', white=True)
p.label(p.xy(w_zero)+[.13,.27], r'$q_2=0$', 'text=dhgold,anchor=west')
p.label(p.xy(S+.59*(w_zero-S))+[-.13,.23], r'$u$', 'text=dhgold,fill=white')
p.label(p.xy(S+R0@ry(Q2*.55)@U)+[.44,.04], r'$q_2$', 'text=dhpurple')
p.worldline(S, W, 'vector')
p.label(p.xy(S+.57*(W-S))+[.14,-.25], r'$r=(X,Y,Z)^T$', 'text=dhpurple,fill=white')
p.axis(S, R0@EY, U[1]+.36, r'$y_s$', 'dhgreen', (.05,.14))
p.dot(center, 'dhgreen', '1.3pt')
p.label(p.xy(center)+[-.25,.18], r'$(0,Y,0)$', 'text=dhgreen,anchor=south east')
p.dot(S, radius='1.4pt')
p.dot(W, 'dhpurple', '2pt', white=True)
p.label(p.xy(S)+[-.12,-.23], r'$S$', 'anchor=north,fill=white')
p.label(p.xy(W)+[.26,-.02], r'$W$', 'text=dhpurple,anchor=west')
p.label([3.95,6.70], r'$Y$ unchanged,\quad $\|r\|=\|u\|$', 'text=dhink')
p.label([3.95,6.25], r'\scriptsize Hold $q_3$ fixed and vary only $q_2$.', 'text=dhgray')
p.save()


# (c) True orthographic projection onto x_s z_s, with the same q2 and q3.
p = Panel('ik_shoulder_projection.tex', [1.1,2.0], scale=1.40, width=8.4, height=5.25)
v0 = np.array([AVAL,0.,D3])
v1 = np.array([R[0],0.,R[2]])
p.worldline(np.array([-.18,0,0]), np.array([3.8,0,0]), 'axis,dhgray!65')
p.worldline(np.array([0,0,-.9]), np.array([0,0,1.7]), 'axis,dhgray!65')
p.label(p.xy(np.array([3.8,0,0]))+[.10,-.13], r'$x_s$\;($X$)', 'text=dhred,anchor=west')
p.label(p.xy(np.array([0,0,1.7]))+[0.,.14], r'$z_s$\;($Z$)', 'text=dhblue')
p.worldline(O, v0, 'dhgold,line width=.9pt,-{Latex[length=2mm]}')
p.worldline(O, v1, 'vector')
p.dot(O, radius='1pt')
p.dot(v0, 'dhgold', '1.5pt')
p.dot(v1, 'dhpurple', '1.5pt')
p.label(p.xy(v0)+[.15,.15], r'$(A,d_3)$', 'text=dhgold,anchor=west')
p.label(p.xy(v1)+[.16,-.16], r'$(X,Z)$', 'text=dhpurple,anchor=west')
theta0 = math.atan2(D3, AVAL)
p.curve([.98*np.array([math.cos(t),0,math.sin(t)])
         for t in np.linspace(theta0,theta0-Q2,50)],
        'dhpurple,line width=.8pt,-{Latex[length=1.6mm]}')
p.label(p.xy(np.array([1.4,0,.18])), r'$q_2$', 'text=dhpurple')
p.label([4.0,.20], r'\scriptsize Positive $q_2$ is clockwise in this projection.', 'text=dhgray')
p.save()


# Independent verification against the URDF joint origins and axes.
robot = ET.parse(ROOT/'CuRo6R'/'CuRo6R.urdf').getroot()
transform = np.eye(4)
origins, axes = [], []
for i, angle in enumerate([Q1,Q2,Q3,0.,0.], 1):
    joint = robot.find(f"joint[@name='joint_{i}']")
    xyz = np.fromstring(joint.find('origin').get('xyz'), sep=' ')
    roll,pitch,yaw = np.fromstring(joint.find('origin').get('rpy'), sep=' ')
    fixed = np.eye(4)
    fixed[:3,:3] = rz(yaw)@ry(pitch)@rx(roll)
    fixed[:3,3] = xyz
    transform = transform@fixed
    axis = np.fromstring(joint.find('axis').get('xyz'), sep=' ')
    origins.append(transform[:3,3].copy())
    axes.append(transform[:3,:3]@axis)
    moving = np.eye(4)
    moving[:3,:3] = rotation(axis, angle)
    transform = transform@moving
expected_origins = np.array([J1,S,E,J4,W])
expected_axes = np.array([EZ,R0@EY,R2@EZ,R3@EX,R3@EZ])
origin_error = np.max(np.abs(np.array(origins)-expected_origins))
axis_error = np.max(np.abs(np.array(axes)-expected_axes))
assert origin_error < 1e-9 and axis_error < 1e-9
assert np.allclose(R, ry(Q2)@U)
assert abs(R[1]-U[1]) < 1e-12
assert abs(np.dot(R,R)-np.dot(U,U)) < 1e-12
recovered_q2 = math.atan2(D3*R[0]-AVAL*R[2], AVAL*R[0]+D3*R[2])
assert abs(recovered_q2-Q2) < 1e-12
assert abs(math.atan2(R[2],R[0])-theta0+Q2) < 1e-12
print('Generated three TikZ panels, q = (40, 25, 75) degrees.')
print(f'URDF maximum position/axis errors: {origin_error:.3e}, {axis_error:.3e}')
print(f'W in base = {W}; r in shoulder frame = {R}')
print('Verified Y and norm invariance, and clockwise q2 recovery in the XZ projection.')
