"""Generate the six editable TikZ panels from one shared DH home geometry.

Run from any directory with Python 3 + NumPy. Rendering needs no Python: the
generated .tex files are committed sources and are directly included by LaTeX.
All panels use the same projection, length scale, axes and joint-cylinder macro.
"""
from pathlib import Path
import math
import numpy as np

OUT = Path(__file__).resolve().parent
PI = math.pi
D = [1, 1.25, .75, 2.5, 0, 1.5]
A = [.8, 2, 0, 0, 0, 0]
THETA = [0, 0, PI/2, 0, 0, 0]
ALPHA = [-PI/3, PI/2, PI/2, -PI/2, PI/2, 0]
# One oblique projection for every panel: base x is horizontal, base z is
# vertical, and base y recedes diagonally. Only the view changes, not the DH frames.
PROJ = np.array([[1, .45, 0], [0, .50, 1]])
SCALE = 1.5

def rx(t):
    c, s = math.cos(t), math.sin(t)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])

def rz(t):
    c, s = math.cos(t), math.sin(t)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])

R = [np.eye(3)]
O = [np.zeros(3)]
for d, a, t, al in zip(D, A, THETA, ALPHA):
    O.append(O[-1] + R[-1] @ np.array([a*math.cos(t), a*math.sin(t), d]))
    R.append(R[-1] @ rz(t) @ rx(al))
O, R = np.array(O), np.array(R)
P = {1: np.array([0, 0, .5]), 2: O[1], 3: O[2],
     4: O[3]+1.5*R[3,:,2], 5: O[4], 6: O[6]}

def pt(v):
    return '(' + ','.join(f'{float(x):.4f}' for x in v) + ')'

class Panel:
    def __init__(self, i, reference, shift):
        self.i, self.ref, self.shift = i, reference, np.array(shift)
        self.lines = [r'% Generated by generate_dh_diagrams.py; editable TikZ.',
            r'\begin{tikzpicture}[x=1cm,y=1cm,>=Latex,font=\footnotesize,',
            r' axis/.style={line width=.65pt,-{Latex[length=1.5mm]}},',
            r' ext/.style={dhgray,densely dashed,line width=.45pt},',
            r' dim/.style={dhgold,line width=.5pt,{Latex[length=1.2mm]}-{Latex[length=1.2mm]}},',
            r' every node/.style={inner sep=1.1pt}]',
            r'\path[use as bounding box] (0,0) rectangle (8.2,4.45);']

    def xy(self, p):
        return self.shift + SCALE * PROJ @ (np.array(p)-self.ref)

    def line(self, p, q, style):
        self.lines.append(r'\draw['+style+'] '+pt(p)+' -- '+pt(q)+';')

    def label(self, p, label, opts=''):
        self.lines.append(r'\node['+opts+'] at '+pt(p)+' {'+label+'};')

    def extension(self, p, q):
        self.line(self.xy(p), self.xy(q), 'ext')

    def joint(self, j, labeloffset=(0,-.4)):
        p = self.xy(P[j])
        w = PROJ @ R[j-1,:,2]
        angle = math.degrees(math.atan2(w[1],w[0]))
        self.lines += [r'\begin{scope}[shift={'+pt(p)+'},rotate='+f'{angle:.4f}'+']',
            r'\path[draw=dhgray,fill=dhgray!12,line width=.5pt] (-.26,-.19) -- (.26,-.19) arc[start angle=-90,end angle=90,x radius=.075,y radius=.19] -- (-.26,.19) arc[start angle=90,end angle=270,x radius=.075,y radius=.19];',
            r'\draw[dhgray,fill=white,line width=.5pt] (.26,0) ellipse[x radius=.075,y radius=.19];',
            r'\end{scope}']
        self.label(p+np.array(labeloffset),r'$\jointid{'+str(j)+'}$','text=dhgray,fill=white,inner sep=.7pt')

    def vector(self, origin, vector, label, color, labeloffset=None, length=.72):
        v = length*(PROJ @ vector)
        end = origin+v
        self.line(origin, end, 'axis,'+color)
        if labeloffset is None:
            labeloffset = .12*v/max(np.linalg.norm(v),.001)
        self.label(end+np.array(labeloffset),label,'text='+color+',fill=white,inner sep=.7pt')

    def frame(self, f, offsets=None, originlabel=None, lengths=(.72,.72,.72)):
        p = self.xy(O[f])
        for k, color in enumerate(['dhred','dhgreen','dhblue']):
            lab = '$'+['x','y','z'][k]+'_{'+str(f)+'}$'
            self.vector(p,R[f,:,k],lab,color, None if offsets is None else offsets[k], lengths[k])
        self.lines.append(r'\fill[dhink] '+pt(p)+' circle[radius=1.15pt];')
        offset = np.array([-.12,-.28]) if originlabel is None else np.array(originlabel)
        self.label(p+offset,'$O_{'+str(f)+'}$','text=dhink,fill=white,fill opacity=.85,text opacity=1')

    def dim(self, p, q, offset, label, labeloffset=(0,0)):
        p, q, offset = self.xy(p), self.xy(q), np.array(offset)
        for a in (p,q):
            self.line(a, a+offset, 'dhgold!55,line width=.35pt')
        self.line(p+offset, q+offset, 'dim')
        self.label((p+q)/2+offset+np.array(labeloffset),label,
                   'text=dhgold,fill=white,inner sep=1.8pt')

    def twist(self):
        i = self.i
        c = np.array([6.85,2.8])
        self.lines.append(r'\path[draw=dhgray!25,fill=dhgray!3,rounded corners=2pt,line width=.3pt] (5.8,2.18) rectangle (8.12,4.38);')
        angle = ['-60^\\circ','+90^\\circ','+90^\\circ','-90^\\circ','+90^\\circ','0'][i-1]
        self.label([6.96,4.15],r'$\alpha_{'+str(i)+'}='+angle+'$', 'text=dhpurple')
        x, z0, z1 = R[i,:,0], R[i-1,:,2], R[i,:,2]
        if i < 6:
            self.vector(c,z0,'$z_{'+str(i-1)+'}$','dhgray',[-.10,.13] if i == 1 else None)
            self.vector(c,z1,'$z_{'+str(i)+'}$','dhblue',[.14,.09] if i == 1 else None)
            arc = []
            for t in np.linspace(0, ALPHA[i-1], 45):
                v = z0*math.cos(t)+np.cross(x,z0)*math.sin(t)
                arc.append(pt(c+.42*PROJ@v))
            self.lines.append(r'\draw[dhpurple,line width=.6pt,-{Latex[length=1.2mm]}] '+' -- '.join(arc)+';')
        else:
            self.vector(c,z1,'$z_5=z_6$','dhblue',[-.05,.18])
        self.vector(c,x,'$x_{'+str(i)+'}$','dhred')
        self.lines.append(r'\fill[dhink] '+pt(c)+' circle[radius=.8pt];')

    def save(self):
        self.twist()
        self.lines.append(r'\end{tikzpicture}')
        (OUT/f'dh_step_{self.i}.tex').write_text('\n'.join(self.lines)+'\n')

# 1: retain the physical first joint half-way up the first DH offset.
p = Panel(1,O[0],[1.55,1.00])
b = O[0]+D[0]*R[0,:,2]
p.extension(O[0],b)
p.line(p.xy(b),p.xy(O[1]),'dhgray,line width=1pt')
p.joint(1,[.40,-.02]); p.joint(2,[.50,.25])
p.dim(O[0],b,[-.55,0],r'$d_1=1$',[-.1,0])
p.dim(b,O[1],[0,.62],r'$a_1=0.8$')
p.frame(0,originlabel=[-.08,-.27],lengths=(.72,.72,1.15)); p.frame(1,originlabel=[-.20,-.32])
p.label([4.25,.72],r'$d_1=0.5+0.5$', 'text=dhgold')
p.save()

# 2: the common-normal construction is drawn in DH order, d then a.
p = Panel(2,O[1],[.95,1.10])
b = O[1]+D[1]*R[1,:,2]
p.extension(O[1],b)
p.line(p.xy(b),p.xy(O[2]),'dhgray,line width=1pt')
p.joint(2,[-.35,-.25]); p.joint(3,[.28,-.40])
p.dim(O[1],b,[-.47,.07],r'$d_2=1.25$',[-.03,.23])
p.dim(b,O[2],[0,.64],r'$a_2=2$')
p.frame(1,originlabel=[-.30,-.63]); p.frame(2,originlabel=[-.20,-.30])
p.save()

# 3: DH origin at the extended-axis intersection, not at joint 4.
p = Panel(3,O[2],[1.85,1.20])
b = O[2]+1.5*R[2,:,0]
p.line(p.xy(O[2]),p.xy(b),'dhgray!65,line width=1pt')
p.line(p.xy(b),p.xy(P[4]),'dhgray!65,line width=1pt')
p.extension(O[2],O[3]+.6*R[2,:,2])
p.extension(O[3],P[4]+.4*R[3,:,2])
p.joint(3,[-.20,-.35]); p.joint(4,[.1,-.42])
p.dim(O[2],O[3],[-.60,-.08],r'$d_3=0.75$',[-.15,0])
p.dim(O[3],P[4],[0,-1.18],r'$1.5$')
p.frame(2,offsets=[[.10,-.04],[.12,-.10],[.15,.06]],originlabel=[.45,-.28],lengths=(.72,.46,.72))
p.frame(3,offsets=[[.04,.18],[-.17,.05],[.12,.06]],originlabel=[-.18,.06])
p.label([3.98,2.58],r'$a_3=0$', 'text=dhgold')
p.label([3.98,4.15],r'$\theta_3^0=+90^\circ$', 'text=dhpurple')
c = np.array([3.75,3.05])
p.vector(c,R[2,:,0],r'$x_2$','dhgray')
p.vector(c,R[3,:,0],r'$x_3$','dhred')
arc = [pt(c+.42*PROJ@(R[2,:,0]*math.cos(t)+R[2,:,1]*math.sin(t)))
       for t in np.linspace(0,PI/2,45)]
p.lines.append(r'\draw[dhpurple,line width=.6pt,-{Latex[length=1.2mm]}] '+' -- '.join(arc)+';')
p.lines.append(r'\fill[dhink] '+pt(c)+' circle[radius=.8pt];')
p.save()

# 4: same joint-4 cylinder and frame 3 as in panel 3.
p = Panel(4,O[3],[.95,2.12])
p.extension(O[3],P[4])
p.line(p.xy(P[4]),p.xy(P[5]),'dhgray,line width=1pt')
p.joint(4,[0,-.42]); p.joint(5,[.45,-.12])
p.dim(O[3],O[4],[0,-1.17],r'$d_4=2.5$')
p.dim(O[3],P[4],[0,1.25],r'$1.5$')
p.dim(P[4],P[5],[0,1.25],r'$1$')
p.frame(3,originlabel=[-.12,-.29]); p.frame(4,originlabel=[.12,-.55])
p.save()

# 5: overlapping frames are drawn explicitly with shared-direction labels.
p = Panel(5,O[4],[1.60,2.12])
p.extension(P[5],P[6]+.4*R[5,:,2])
p.joint(5,[.50,.25]); p.joint(6,[0,-.43])
c = p.xy(O[4])
p.vector(c,R[4,:,0],r'$x_4=x_5$','dhred',[.13,.17])
p.vector(c,R[4,:,1],r'$y_4$','dhgreen',[-.14,0])
p.vector(c,R[4,:,2],r'$\textcolor{dhblue}{z_4}=\textcolor{dhgreen}{y_5}$','dhblue',[-.26,.12])
p.vector(c,R[5,:,2],r'$z_5$','dhblue',[.13,.08])
p.lines.append(r'\fill[dhink] '+pt(c)+' circle[radius=1.15pt];')
p.label(c+[-.08,-.45],r'$O_4=O_5$','fill=white,text=dhink')
p.dim(P[5],P[6],[0,-1.05],r'centres: $1.5$')
p.label([2.50,3.78],r'$d_5=a_5=0$', 'text=dhgold')
p.save()

# 6: keep both wrist cylinders to make the continuity of the last pair clear.
p = Panel(6,O[5],[1.60,2.12])
p.extension(P[5],P[6]+.4*R[5,:,2])
p.joint(5,[-.43,-.04]); p.joint(6,[.20,-.42])
p.dim(O[5],O[6],[0,-1.05],r'$d_6=1.5$')
p.frame(5,originlabel=[-.14,-.43]); p.frame(6,originlabel=[-.20,-.27])
p.label([3.12,3.78],r'$O_6=O_E$', 'text=dhink')
p.save()

# Numerical invariants guard sign and indexing mistakes in the drawings.
expected_axes = np.array([[0,0,1],[0,math.sqrt(3)/2,.5],
                         [0,-.5,math.sqrt(3)/2],[1,0,0],
                         [0,-.5,math.sqrt(3)/2],[1,0,0]])
assert np.allclose(R[:6,:,2],expected_axes)
assert np.allclose(O[4],O[5])
assert np.allclose(O[3]+1.5*R[3,:,2],P[4])
assert np.allclose(R[6] @ np.array([[0,1,0],[0,0,1],[1,0,0]]),rx(PI/6))
print('Generated six consistent home-configuration TikZ panels.')
