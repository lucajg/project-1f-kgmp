function export_connectivity_linear
% Reproduce the report's straight-arm experiment using the active planner.
% From the repository root:
%   addpath('report/figures'); export_connectivity_linear
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(fullfile(root,'Matlab'));
curo6r_setup;
q_start = [0.1024;-1.1124;1.8547;-1.4399;-0.3835;-2.6486];
[path,goal,candidates] = path_between_to_ik_solutions(q_start, ...
    n_samples=10000,plot_results=false);
assert(~isempty(path),'The report example no longer passes.');
poe = poe_data;
dh = dh_data;
target = poe_fk(q_start,poe);
max_dh_position = 0;
max_dh_orientation = 0;
for k = 1:numel(path.s)
    T = dh_fk(path.q(:,k),dh);
    max_dh_position = max(max_dh_position,norm(T(1:3,4)-path.p(:,k)));
    max_dh_orientation = max(max_dh_orientation, ...
        norm(T(1:3,1:3)-target(1:3,1:3),'fro'));
end
assert(max_dh_position < 1e-10 && max_dh_orientation < 1e-10);
summary = struct('n_samples',numel(path.s),'sigma_tol',1e-3, ...
    'singular_tol',1e-6,'length_scale_m',2, ...
    'min_sigma',min(path.sigma_min), ...
    'min_joint_margin_rad',min(path.joint_margin), ...
    'min_abs_wrist_sine',min(abs(sin(path.q(5,:)))), ...
    'min_abs_arm_det',min(abs(path.arm_det)), ...
    'max_orientation_error_rad',max(path.theta), ...
    'max_position_consistency_m',max(path.error_position), ...
    'position_closure_m',norm(path.p(:,end)-path.p(:,1)), ...
    'goal_error_rad',path.goal_error, ...
    'max_dh_position_error_m',max_dh_position, ...
    'max_dh_orientation_frobenius',max_dh_orientation);
% Keep a modest plotting grid; all summary extrema use the full sample grid.
idx = unique([1:10:numel(path.s),numel(path.s)]);
data = struct('q_start',q_start,'q_goal',goal,'target',target, ...
    'Q_ik',candidates.Goal.','selected_id',find(candidates.Selected), ...
    'outcomes',candidates.Outcome,'statuses',candidates.Status, ...
    'summary',summary,'s',path.s(idx),'q',path.q(:,idx), ...
    'p',path.p(:,idx),'sigma_min',path.sigma_min(idx), ...
    'joint_margin',path.joint_margin(idx),'arm_det',path.arm_det(idx));
filename = fullfile(here,'connectivity_linear_data.json');
fid = fopen(filename,'w');
assert(fid >= 0,'Cannot open report data file.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',jsonencode(data,PrettyPrint=true));
disp(summary);
fprintf('Report data: %s\n',filename);
end
